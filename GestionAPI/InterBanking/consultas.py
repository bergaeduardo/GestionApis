"""
Consultas SQL para el módulo InterBanking.
Tabla destino: BI_T_SALDOS_INTERBANKING
"""

# Crea la tabla si no existe (ejecutar una sola vez)
QRY_CREATE_TABLE = """
IF NOT EXISTS (
    SELECT 1 FROM INFORMATION_SCHEMA.TABLES
    WHERE TABLE_NAME = 'BI_T_SALDOS_INTERBANKING'
)
CREATE TABLE BI_T_SALDOS_INTERBANKING (
    ID                       BIGINT IDENTITY(1,1) PRIMARY KEY,
    FECHA_OPERACION          DATE           NOT NULL,
    NRO_BANCO                VARCHAR(10)    NOT NULL,
    NRO_CUENTA               VARCHAR(50)    NOT NULL,
    TIPO_CUENTA              VARCHAR(5)     NULL,
    MONEDA                   VARCHAR(5)     NULL,
    LABEL_CUENTA             VARCHAR(100)   NULL,
    NOMBRE_CUENTA            VARCHAR(100)   NULL,
    SALDO_CONTABLE           DECIMAL(18,2)  NULL,
    SALDO_OPERATIVO_INICIAL  DECIMAL(18,2)  NULL,
    SALDO_OPERATIVO_ACTUAL   DECIMAL(18,2)  NULL,
    SALDO_PROYECTADO_24HS    DECIMAL(18,2)  NULL,
    SALDO_PROYECTADO_48HS    DECIMAL(18,2)  NULL,
    SALDO_DIA                DECIMAL(18,2)  NULL,
    TOTAL_DEBITOS            DECIMAL(18,2)  NULL,
    TOTAL_CREDITOS           DECIMAL(18,2)  NULL,
    CREATED_AT               DATETIME       DEFAULT GETDATE()
)
"""

# MERGE por (FECHA_OPERACION, NRO_BANCO, NRO_CUENTA): upsert idempotente
QRY_MERGE_SALDO = """
MERGE INTO BI_T_SALDOS_INTERBANKING AS target
USING (
    SELECT
        ?  AS FECHA_OPERACION,
        ?  AS NRO_BANCO,
        ?  AS NRO_CUENTA,
        ?  AS TIPO_CUENTA,
        ?  AS MONEDA,
        ?  AS LABEL_CUENTA,
        ?  AS NOMBRE_CUENTA,
        ?  AS SALDO_CONTABLE,
        ?  AS SALDO_OPERATIVO_INICIAL,
        ?  AS SALDO_OPERATIVO_ACTUAL,
        ?  AS SALDO_PROYECTADO_24HS,
        ?  AS SALDO_PROYECTADO_48HS,
        ?  AS SALDO_DIA,
        ?  AS TOTAL_DEBITOS,
        ?  AS TOTAL_CREDITOS
) AS source
ON  target.FECHA_OPERACION = source.FECHA_OPERACION
AND target.NRO_BANCO       = source.NRO_BANCO
AND target.NRO_CUENTA      = source.NRO_CUENTA
WHEN MATCHED THEN
    UPDATE SET
        TIPO_CUENTA             = source.TIPO_CUENTA,
        MONEDA                  = source.MONEDA,
        LABEL_CUENTA            = source.LABEL_CUENTA,
        NOMBRE_CUENTA           = source.NOMBRE_CUENTA,
        SALDO_CONTABLE          = source.SALDO_CONTABLE,
        SALDO_OPERATIVO_INICIAL = source.SALDO_OPERATIVO_INICIAL,
        SALDO_OPERATIVO_ACTUAL  = source.SALDO_OPERATIVO_ACTUAL,
        SALDO_PROYECTADO_24HS   = source.SALDO_PROYECTADO_24HS,
        SALDO_PROYECTADO_48HS   = source.SALDO_PROYECTADO_48HS,
        SALDO_DIA               = source.SALDO_DIA,
        TOTAL_DEBITOS           = source.TOTAL_DEBITOS,
        TOTAL_CREDITOS          = source.TOTAL_CREDITOS,
        CREATED_AT              = GETDATE()
WHEN NOT MATCHED THEN
    INSERT (
        FECHA_OPERACION, NRO_BANCO, NRO_CUENTA, TIPO_CUENTA, MONEDA,
        LABEL_CUENTA, NOMBRE_CUENTA, SALDO_CONTABLE, SALDO_OPERATIVO_INICIAL,
        SALDO_OPERATIVO_ACTUAL, SALDO_PROYECTADO_24HS, SALDO_PROYECTADO_48HS,
        SALDO_DIA, TOTAL_DEBITOS, TOTAL_CREDITOS, CREATED_AT
    )
    VALUES (
        source.FECHA_OPERACION, source.NRO_BANCO, source.NRO_CUENTA,
        source.TIPO_CUENTA, source.MONEDA, source.LABEL_CUENTA, source.NOMBRE_CUENTA,
        source.SALDO_CONTABLE, source.SALDO_OPERATIVO_INICIAL, source.SALDO_OPERATIVO_ACTUAL,
        source.SALDO_PROYECTADO_24HS, source.SALDO_PROYECTADO_48HS,
        source.SALDO_DIA, source.TOTAL_DEBITOS, source.TOTAL_CREDITOS, GETDATE()
    );
"""


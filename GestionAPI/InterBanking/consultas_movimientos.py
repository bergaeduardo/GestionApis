"""
Consultas SQL para el módulo de Movimientos InterBanking.
Tabla destino: BI_T_MOVIMIENTOS_INTERBANKING
"""

QRY_CREATE_TABLE_MOVIMIENTOS = """
IF NOT EXISTS (
    SELECT 1 FROM INFORMATION_SCHEMA.TABLES
    WHERE TABLE_NAME = 'BI_T_MOVIMIENTOS_INTERBANKING'
)
CREATE TABLE BI_T_MOVIMIENTOS_INTERBANKING (
    ID                   BIGINT IDENTITY(1,1) PRIMARY KEY,
    NRO_BANCO            VARCHAR(10)     NOT NULL,
    NRO_CUENTA           VARCHAR(50)     NOT NULL,
    TIPO_CUENTA          VARCHAR(5)      NULL,
    MONEDA               VARCHAR(5)      NULL,
    TIPO_MOVIMIENTO      VARCHAR(20)     NOT NULL,
    ID_MOVIMIENTO        BIGINT          NOT NULL,
    FECHA_PROCESO        DATETIME        NULL,
    TIPO_DEB_CRED        VARCHAR(1)      NULL,
    IMPORTE              DECIMAL(18,2)   NULL,
    NRO_COMPROBANTE      BIGINT          NULL,
    COD_OPERACION_IB     VARCHAR(50)     NULL,
    COD_OPERACION_BANCO  VARCHAR(50)     NULL,
    DESC_OPERACION_IB    VARCHAR(255)    NULL,
    DESC_OPERACION_BANCO VARCHAR(255)    NULL,
    CBU_CUENTA           VARCHAR(50)     NULL,
    COD_DEPOSITANTE      VARCHAR(50)     NULL,
    DESC_DEPOSITANTE     VARCHAR(255)    NULL,
    CUIT_CLIENTE         VARCHAR(20)     NULL,
    COD_AGRUPAMIENTO_IB  VARCHAR(50)     NULL,
    SUCURSAL             VARCHAR(100)    NULL,
    CREATED_AT           DATETIME        DEFAULT GETDATE()
)
"""

# Migración: corrige ID_MOVIMIENTO de INT a BIGINT si la tabla fue creada con la versión anterior
QRY_MIGRATE_ID_TO_BIGINT = """
IF EXISTS (
    SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_NAME  = 'BI_T_MOVIMIENTOS_INTERBANKING'
      AND COLUMN_NAME = 'ID_MOVIMIENTO'
      AND DATA_TYPE   = 'int'
)
    ALTER TABLE BI_T_MOVIMIENTOS_INTERBANKING ALTER COLUMN ID_MOVIMIENTO BIGINT NOT NULL
"""

# MERGE por (NRO_BANCO, NRO_CUENTA, TIPO_CUENTA, MONEDA, TIPO_MOVIMIENTO, ID_MOVIMIENTO)
QRY_MERGE_MOVIMIENTO_DIA = """
MERGE INTO BI_T_MOVIMIENTOS_INTERBANKING AS target
USING (
    SELECT
        ?  AS NRO_BANCO,
        ?  AS NRO_CUENTA,
        ?  AS TIPO_CUENTA,
        ?  AS MONEDA,
        ?  AS TIPO_MOVIMIENTO,
        ?  AS ID_MOVIMIENTO,
        ?  AS FECHA_PROCESO,
        ?  AS TIPO_DEB_CRED,
        ?  AS IMPORTE,
        ?  AS NRO_COMPROBANTE,
        ?  AS COD_OPERACION_IB,
        ?  AS COD_OPERACION_BANCO,
        ?  AS DESC_OPERACION_IB,
        ?  AS DESC_OPERACION_BANCO,
        ?  AS CBU_CUENTA,
        ?  AS COD_DEPOSITANTE,
        ?  AS DESC_DEPOSITANTE,
        ?  AS CUIT_CLIENTE,
        ?  AS COD_AGRUPAMIENTO_IB,
        ?  AS SUCURSAL
) AS source
ON  target.NRO_BANCO        = source.NRO_BANCO
AND target.NRO_CUENTA       = source.NRO_CUENTA
AND target.TIPO_CUENTA      = source.TIPO_CUENTA
AND target.MONEDA           = source.MONEDA
AND target.TIPO_MOVIMIENTO  = source.TIPO_MOVIMIENTO
AND target.ID_MOVIMIENTO    = source.ID_MOVIMIENTO
WHEN MATCHED THEN
    UPDATE SET
        FECHA_PROCESO        = source.FECHA_PROCESO,
        TIPO_DEB_CRED        = source.TIPO_DEB_CRED,
        IMPORTE              = source.IMPORTE,
        NRO_COMPROBANTE      = source.NRO_COMPROBANTE,
        COD_OPERACION_IB     = source.COD_OPERACION_IB,
        COD_OPERACION_BANCO  = source.COD_OPERACION_BANCO,
        DESC_OPERACION_IB    = source.DESC_OPERACION_IB,
        DESC_OPERACION_BANCO = source.DESC_OPERACION_BANCO,
        CBU_CUENTA           = source.CBU_CUENTA,
        COD_DEPOSITANTE      = source.COD_DEPOSITANTE,
        DESC_DEPOSITANTE     = source.DESC_DEPOSITANTE,
        CUIT_CLIENTE         = source.CUIT_CLIENTE,
        COD_AGRUPAMIENTO_IB  = source.COD_AGRUPAMIENTO_IB,
        SUCURSAL             = source.SUCURSAL,
        CREATED_AT           = GETDATE()
WHEN NOT MATCHED THEN
    INSERT (
        NRO_BANCO, NRO_CUENTA, TIPO_CUENTA, MONEDA, TIPO_MOVIMIENTO,
        ID_MOVIMIENTO, FECHA_PROCESO, TIPO_DEB_CRED, IMPORTE,
        NRO_COMPROBANTE, COD_OPERACION_IB, COD_OPERACION_BANCO,
        DESC_OPERACION_IB, DESC_OPERACION_BANCO, CBU_CUENTA,
        COD_DEPOSITANTE, DESC_DEPOSITANTE, CUIT_CLIENTE,
        COD_AGRUPAMIENTO_IB, SUCURSAL, CREATED_AT
    )
    VALUES (
        source.NRO_BANCO, source.NRO_CUENTA, source.TIPO_CUENTA,
        source.MONEDA, source.TIPO_MOVIMIENTO, source.ID_MOVIMIENTO,
        source.FECHA_PROCESO, source.TIPO_DEB_CRED, source.IMPORTE,
        source.NRO_COMPROBANTE, source.COD_OPERACION_IB, source.COD_OPERACION_BANCO,
        source.DESC_OPERACION_IB, source.DESC_OPERACION_BANCO, source.CBU_CUENTA,
        source.COD_DEPOSITANTE, source.DESC_DEPOSITANTE, source.CUIT_CLIENTE,
        source.COD_AGRUPAMIENTO_IB, source.SUCURSAL, GETDATE()
    );
"""

# Cuentas conocidas: obtiene la lista desde BI_T_SALDOS_INTERBANKING
QRY_OBTENER_CUENTAS = """
SELECT DISTINCT NRO_BANCO, NRO_CUENTA, TIPO_CUENTA, MONEDA
FROM BI_T_SALDOS_INTERBANKING
ORDER BY NRO_BANCO, NRO_CUENTA
"""


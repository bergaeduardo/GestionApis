"""
Consultas SQL para el módulo de Extractos InterBanking.
Tabla destino: BI_T_EXTRACTOS_INTERBANKING
"""

# Crea la tabla si no existe (ejecutar una sola vez)
QRY_CREATE_TABLE_EXTRACTOS = """
IF NOT EXISTS (
    SELECT 1 FROM INFORMATION_SCHEMA.TABLES
    WHERE TABLE_NAME = 'BI_T_EXTRACTOS_INTERBANKING'
)
CREATE TABLE BI_T_EXTRACTOS_INTERBANKING (
    ID                   BIGINT IDENTITY(1,1) PRIMARY KEY,
    FECHA_OPERACION      DATE            NOT NULL,
    NRO_BANCO            VARCHAR(10)     NOT NULL,
    NRO_CUENTA           VARCHAR(50)     NOT NULL,
    TIPO_CUENTA          VARCHAR(5)      NULL,
    MONEDA               VARCHAR(5)      NULL,
    NRO_EXTRACTO         VARCHAR(20)     NULL,
    SALDO_INICIAL        DECIMAL(18,2)   NULL,
    SALDO_FINAL          DECIMAL(18,2)   NULL,
    DEB_TOTAL_DIA        DECIMAL(18,2)   NULL,
    CRED_TOTAL_DIA       DECIMAL(18,2)   NULL,
    NRO_CORRELATIVO      BIGINT          NOT NULL,
    NRO_COMPROBANTE      BIGINT          NULL,
    FECHA_MOVIMIENTO     DATETIME        NULL,
    FECHA_VALOR          DATETIME        NULL,
    TIPO_MOV             VARCHAR(1)      NULL,
    IMPORTE              DECIMAL(18,2)   NULL,
    COD_OPERACION_IB     VARCHAR(50)     NULL,
    COD_OPERACION_BANCO  VARCHAR(50)     NULL,
    DESC_OPERACION       VARCHAR(255)    NULL,
    DESC_DEPOSITANTE     VARCHAR(255)    NULL,
    CUIT_CLIENTE         VARCHAR(20)     NULL,
    SUCURSAL             VARCHAR(100)    NULL,
    CREATED_AT           DATETIME        DEFAULT GETDATE()
)
"""

# MERGE por (NRO_BANCO, NRO_CUENTA, FECHA_OPERACION, NRO_CORRELATIVO)
QRY_MERGE_MOVIMIENTO = """
MERGE INTO BI_T_EXTRACTOS_INTERBANKING AS target
USING (
    SELECT
        ?  AS FECHA_OPERACION,
        ?  AS NRO_BANCO,
        ?  AS NRO_CUENTA,
        ?  AS TIPO_CUENTA,
        ?  AS MONEDA,
        ?  AS NRO_EXTRACTO,
        ?  AS SALDO_INICIAL,
        ?  AS SALDO_FINAL,
        ?  AS DEB_TOTAL_DIA,
        ?  AS CRED_TOTAL_DIA,
        ?  AS NRO_CORRELATIVO,
        ?  AS NRO_COMPROBANTE,
        ?  AS FECHA_MOVIMIENTO,
        ?  AS FECHA_VALOR,
        ?  AS TIPO_MOV,
        ?  AS IMPORTE,
        ?  AS COD_OPERACION_IB,
        ?  AS COD_OPERACION_BANCO,
        ?  AS DESC_OPERACION,
        ?  AS DESC_DEPOSITANTE,
        ?  AS CUIT_CLIENTE,
        ?  AS SUCURSAL
) AS source
ON  target.NRO_BANCO        = source.NRO_BANCO
AND target.NRO_CUENTA       = source.NRO_CUENTA
AND target.FECHA_OPERACION  = source.FECHA_OPERACION
AND target.NRO_CORRELATIVO  = source.NRO_CORRELATIVO
WHEN MATCHED THEN
    UPDATE SET
        TIPO_CUENTA         = source.TIPO_CUENTA,
        MONEDA              = source.MONEDA,
        NRO_EXTRACTO        = source.NRO_EXTRACTO,
        SALDO_INICIAL       = source.SALDO_INICIAL,
        SALDO_FINAL         = source.SALDO_FINAL,
        DEB_TOTAL_DIA       = source.DEB_TOTAL_DIA,
        CRED_TOTAL_DIA      = source.CRED_TOTAL_DIA,
        NRO_COMPROBANTE     = source.NRO_COMPROBANTE,
        FECHA_MOVIMIENTO    = source.FECHA_MOVIMIENTO,
        FECHA_VALOR         = source.FECHA_VALOR,
        TIPO_MOV            = source.TIPO_MOV,
        IMPORTE             = source.IMPORTE,
        COD_OPERACION_IB    = source.COD_OPERACION_IB,
        COD_OPERACION_BANCO = source.COD_OPERACION_BANCO,
        DESC_OPERACION      = source.DESC_OPERACION,
        DESC_DEPOSITANTE    = source.DESC_DEPOSITANTE,
        CUIT_CLIENTE        = source.CUIT_CLIENTE,
        SUCURSAL            = source.SUCURSAL,
        CREATED_AT          = GETDATE()
WHEN NOT MATCHED THEN
    INSERT (
        FECHA_OPERACION, NRO_BANCO, NRO_CUENTA, TIPO_CUENTA, MONEDA,
        NRO_EXTRACTO, SALDO_INICIAL, SALDO_FINAL, DEB_TOTAL_DIA, CRED_TOTAL_DIA,
        NRO_CORRELATIVO, NRO_COMPROBANTE, FECHA_MOVIMIENTO, FECHA_VALOR,
        TIPO_MOV, IMPORTE, COD_OPERACION_IB, COD_OPERACION_BANCO,
        DESC_OPERACION, DESC_DEPOSITANTE, CUIT_CLIENTE, SUCURSAL, CREATED_AT
    )
    VALUES (
        source.FECHA_OPERACION, source.NRO_BANCO, source.NRO_CUENTA,
        source.TIPO_CUENTA, source.MONEDA, source.NRO_EXTRACTO,
        source.SALDO_INICIAL, source.SALDO_FINAL, source.DEB_TOTAL_DIA,
        source.CRED_TOTAL_DIA, source.NRO_CORRELATIVO, source.NRO_COMPROBANTE,
        source.FECHA_MOVIMIENTO, source.FECHA_VALOR, source.TIPO_MOV,
        source.IMPORTE, source.COD_OPERACION_IB, source.COD_OPERACION_BANCO,
        source.DESC_OPERACION, source.DESC_DEPOSITANTE, source.CUIT_CLIENTE,
        source.SUCURSAL, GETDATE()
    );
"""

# Cuentas conocidas: obtiene la lista desde BI_T_SALDOS_INTERBANKING
QRY_OBTENER_CUENTAS = """
SELECT DISTINCT NRO_BANCO, NRO_CUENTA, TIPO_CUENTA, MONEDA
FROM BI_T_SALDOS_INTERBANKING
ORDER BY NRO_BANCO, NRO_CUENTA
"""

# Verifica movimientos en un rango (testing)
QRY_VERIFICAR_EXTRACTOS = """
SELECT
    FECHA_OPERACION, NRO_BANCO, NRO_CUENTA,
    NRO_CORRELATIVO, TIPO_MOV, IMPORTE, DESC_OPERACION
FROM BI_T_EXTRACTOS_INTERBANKING
WHERE FECHA_OPERACION >= ? AND FECHA_OPERACION <= ?
ORDER BY FECHA_OPERACION DESC, NRO_BANCO, NRO_CUENTA, NRO_CORRELATIVO
"""

